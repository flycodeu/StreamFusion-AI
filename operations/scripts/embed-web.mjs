import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const source = fileURLToPath(new URL("../web/dist/", import.meta.url));
const target = fileURLToPath(
  new URL("../internal/webui/dist/", import.meta.url),
);
if (!existsSync(source + "/index.html")) throw new Error("先构建 web");
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
cpSync(source, target, { recursive: true });
writeFileSync(target + "/.placeholder", "generated by scripts/embed-web.mjs\n");
